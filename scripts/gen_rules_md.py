#!/usr/bin/env python3
"""Generate docs/RULES.md from engine/clauses.metta (rule ids, severities,
topics) and api/kabla/i18n/{en,sw}.json (messages). Stdlib only.

Run after changing a rule or a message:  python scripts/gen_rules_md.py
"""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CLAUSES = ROOT / "engine" / "clauses.metta"
FLAGS = [ROOT / "engine" / "flags.metta", ROOT / "engine" / "redlines.metta"]
I18N = ROOT / "api" / "kabla" / "i18n"
OUT = ROOT / "docs" / "RULES.md"


def rule_comments() -> dict[str, str]:
    """`; R-XXX-01: comment` lines above each rule in the engine sources."""
    found: dict[str, str] = {}
    for path in FLAGS:
        for m in re.finditer(r"^; (R-[A-Z]+-\d+): (.+)$", path.read_text(encoding="utf-8"), re.M):
            found.setdefault(m.group(1), m.group(2).strip())
    return found


def main() -> None:
    rules = re.findall(r"^\(rule-info (\S+) (\S+) (\S+)\)", CLAUSES.read_text(encoding="utf-8"), re.M)
    en = json.loads((I18N / "en.json").read_text(encoding="utf-8"))
    sw = json.loads((I18N / "sw.json").read_text(encoding="utf-8"))
    comments = rule_comments()

    lines = [
        "# Rules",
        "",
        "> Generated by `scripts/gen_rules_md.py` from `engine/clauses.metta`, the rule comments in",
        "> `engine/flags.metta` / `engine/redlines.metta`, and `api/kabla/i18n/{en,sw}.json`. Do not edit by hand.",
        "",
        "Every flag Kabla shows comes from one of these MeTTa rules. The rule id and the clause",
        "number are always shown next to the explanation, so the artist can check the clause herself.",
        "Severity is the rule's base severity; a clause that breaks one of the artist's standing",
        "red lines is raised to **red** and gets an extra trail line citing the date the red line was set.",
        "Swahili text comes from reviewed templates and should be checked by a fluent speaker.",
        "",
        "| Rule | Severity | Topic | What the rule matches |",
        "|---|---|---|---|",
    ]
    for rid, sev, topic in rules:
        lines.append(f"| `{rid}` | {sev} | {topic} | {comments.get(rid, '')} |")
    lines.append("")

    for rid, sev, topic in rules:
        e, s = en["rule"][rid], sw["rule"][rid]
        lines += [
            f"## {rid} ({sev})",
            "",
            f"- **EN:** {e['title']}. {e['meaning']}",
            f"  - *What it costs you:* {e['cost']}",
            f"- **SW:** {s['title']}. {s['meaning']}",
            f"  - *Inakugharimu nini:* {s['cost']}",
            "",
        ]

    lines += [
        "## Red-line trail line",
        "",
        f"- **EN:** {en['redline']['line']}",
        f"- **SW:** {sw['redline']['line']}",
        "",
        "## Licence verdict rules (`engine/licence.metta`)",
        "",
        "| Rule | EN | SW |",
        "|---|---|---|",
    ]
    for rid in ("R-LIC-OK", "R-LIC-CONSENT", "R-LIC-AI", "R-LIC-AI-OPTIN", "R-LIC-TERM"):
        lines.append(f"| `{rid}` | {en['licence'][rid]} | {sw['licence'][rid]} |")
    lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(rules)} flag rules)")


if __name__ == "__main__":
    main()
