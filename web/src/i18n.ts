/** Why this exists: the engine sends enum words ("opt-in-paid", "hold-redline"). Show a plain phrase when we
 *  have one, and let the caller fall back to the raw word when we do not. */
export function tOpt(lang: Lang, key: string): string | undefined {
  return (ui[lang] as Record<string, string>)[key];
}

export function t(lang: Lang, key: keyof typeof ui.en): string {
  return ui[lang][key];
}

/** Why this exists: clerk lines carry live numbers ("Act 2 of 3"), so keys hold {slots}. */
export function tf(lang: Lang, key: keyof typeof ui.en, vars: Record<string, string | number>): string {
  return Object.entries(vars).reduce((s, [k, v]) => s.replaceAll(`{${k}}`, String(v)), t(lang, key));
}
